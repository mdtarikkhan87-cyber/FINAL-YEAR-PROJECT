SYNTHETIC_WARNING = (
    "Models are trained on SYNTHETIC data generated by "
    "src/data_prep/make_synthetic.py. Predictions are not valid for real PERM "
    "cases and must not be used for legal, immigration, or business decisions."
)

# The Next.js dev server runs on a different origin, so the browser will not
# call this API without an explicit CORS allowance. Override for other hosts
# with PERM_API_CORS_ORIGINS as a comma-separated list.
DEFAULT_CORS_ORIGINS = [
    "http://localhost:3000", "http://127.0.0.1:3000",
    "http://localhost:3001", "http://127.0.0.1:3001",
]
CORS_ORIGINS = [
    o.strip() for o in
    os.getenv("PERM_API_CORS_ORIGINS", ",".join(DEFAULT_CORS_ORIGINS)).split(",")
    if o.strip()
]

registry = PredictorRegistry()
store = PredictionStore()


@asynccontextmanager
async def lifespan(app: FastAPI):
    registry.load()
    yield
    store.clear()


app = FastAPI(
    title="PERM Processing Time & Outcome API",
    version="0.1.0",
    description=(
        "Predicts PERM labour-certification processing time and case outcome, with "
        "per-prediction SHAP explanations.\n\n"
        f"**{SYNTHETIC_WARNING}**"
    ),
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=CORS_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["Content-Type"],
)


@app.exception_handler(ModelNotLoadedError)
async def _model_not_loaded(request: Request, exc: ModelNotLoadedError) -> JSONResponse:
    return JSONResponse(status_code=503, content={"detail": str(exc)})


# Python's str.title() mangles the two things these labels are made of:
# "LEVEL III" becomes "Level Iii" and "MASTER'S" becomes "Master'S".
_LABEL_FIXUPS = {"I": "I", "Ii": "II", "Iii": "III", "Iv": "IV"}


def _display(value: str) -> str:
    """Title-case a stored category level for display, preserving roman
    numerals and not capitalising the letter after an apostrophe."""
    words = [_LABEL_FIXUPS.get(w.title(), w.title()) for w in value.split()]
    return " ".join(words).replace("'S", "'s")


def _quality(predictor: BundlePredictor, task: str) -> ModelQuality:
    m, split = predictor.metrics, predictor.split
    trained_on = (f"{split.get('split_on', '?')}-year split, train "
                  f"{split.get('train_years', ['?'])[0]}-{split.get('train_years', ['?'])[-1]}, "
                  f"test {split.get('test_years')}")
    if task == "regression":
        return ModelQuality(
            trained_on=trained_on,
            test_metric=f"RMSE {m.get('test_rmse', float('nan')):.1f} days, "
                        f"MAE {m.get('test_mae', float('nan')):.1f} days",
            baseline_metric=f"RMSE {m.get('baseline_rmse', float('nan')):.1f} days "
                            "(always predict the training median)",
            caveat=(
                "The model beats that baseline by roughly 15%, but its R2 is negative: "
                "it tracks the average better than a constant does, while explaining "
                "little case-to-case variation. Treat the estimate as a rough central "
                "tendency, not a commitment. " + SYNTHETIC_WARNING
            ),
        )
    return ModelQuality(
        trained_on=trained_on,
        test_metric=f"accuracy {m.get('test_accuracy', float('nan')):.3f}, "
                    f"macro-F1 {m.get('test_f1_macro', float('nan')):.3f}, "
                    f"ROC AUC {m.get('test_roc_auc_ovr', float('nan')):.3f}",
        baseline_metric=f"accuracy {m.get('baseline_accuracy', float('nan')):.3f} "
                        "(always predict the majority class)",
        caveat=(
            "This model does NOT beat its baseline. It predicts 'certified' for "
            "essentially every input, and its ROC AUC is close to chance. The "
            "probabilities below are the model's scores and do vary between cases, but "
            "the predicted class is very nearly a constant. Do not read a 'certified' "
            "prediction as evidence the case will be approved. " + SYNTHETIC_WARNING
        ),
    )


