@app.get("/health", response_model=HealthResponse, tags=["meta"])
def health() -> HealthResponse:
    return HealthResponse(
        status="ok" if registry.loaded else "degraded",
        models_loaded=registry.loaded,
        stored_predictions=len(store),
        store_capacity=store.capacity,
        warning=SYNTHETIC_WARNING,
    )


@app.get("/meta/options", response_model=OptionsResponse, tags=["meta"])
def options() -> OptionsResponse:
    """Form options drawn from the model's own category levels.

    A UI that offers a value the model has never seen produces a silently
    degraded prediction, so the choices come from the fitted bundle rather than
    from a hand-maintained list that can drift out of sync with it.
    """
    predictor = registry.regressor or registry.classifier
    if predictor is None:
        raise ModelNotLoadedError("no model is loaded, so options cannot be derived")
    cats = predictor.categories

    def opts(key: str, labeller=None) -> list[FieldOption]:
        return [
            FieldOption(value=v, label=labeller(v) if labeller else v)
            for v in cats.get(key, [])
        ]

    return OptionsResponse(
        soc_codes=opts("soc_code", lambda c: f"{c} - {SOC_CODE_TITLES.get(c, 'Occupation')}"),
        worksite_states=opts("worksite_state",
                             lambda s: f"{s} - {STATE_TO_REGION.get(s, '')}".rstrip(" -")),
        skill_levels=opts("skill_level", _display),
        education_levels=opts("job_education", _display),
        classes_of_admission=opts("class_of_admission"),
        citizenships=opts("citizenship", _display),
        wage_units=[FieldOption(value=u, label=u)
                    for u in ("Year", "Hour", "Month", "Week", "Bi-Weekly")],
        outcome_classes=(registry.classifier.classes if registry.classifier else []) or [],
    )


@app.post("/predict/processing-time", response_model=ProcessingTimeResponse,
          tags=["predict"])
def predict_processing_time(case: CaseInput) -> ProcessingTimeResponse:
    """Predict days from filing to final determination."""
    predictor = registry.require("regressor")
    derived = derive_features(case)
    frame = predictor.build_row(derived)

    days = float(np.clip(predictor.model.predict(frame)[0], 1, None))
    base, shap_values = predictor.shap_for(frame)
    warnings = input_warnings(predictor.features, frame, shap_values,
                              predictor.unseen_categories(derived))

    mae = float(predictor.metrics.get("test_mae", 0.0))
    prediction_id = store.new_id()
    store.put(StoredPrediction(
        prediction_id=prediction_id, task="regression", created_at=utcnow(),
        prediction=days, explained_class=None, base_value=base, units="days",
        contributions=contribution_records(predictor.features, frame, shap_values),
        reconstruction=float(base + shap_values.sum()),
        request=case.model_dump(mode="json"),
    ))

    return ProcessingTimeResponse(
        prediction_id=prediction_id,
        predicted_days=round(days, 1),
        predicted_months=round(days / 30.44, 1),
        likely_range_days=[round(max(1.0, days - mae), 1), round(days + mae, 1)],
        filing_date=case.filing_date,
        estimated_decision_date=estimated_decision_date(case.filing_date, days),
        model_quality=_quality(predictor, "regression"),
        input_warnings=warnings,
        explain_url=f"/explain/{prediction_id}",
    )


@app.post("/predict/outcome", response_model=OutcomeResponse, tags=["predict"])
def predict_outcome(case: CaseInput) -> OutcomeResponse:
    """Predict the case outcome and the probability of each class."""
    predictor = registry.require("classifier")
    derived = derive_features(case)
    frame = predictor.build_row(derived)

    proba = predictor.model.predict_proba(frame)[0]
    classes = predictor.classes or [str(i) for i in range(len(proba))]
    top = int(np.argmax(proba))

    # Explain the predicted class: the contributions that produced this answer.
    base, shap_values = predictor.shap_for(frame, class_index=top)
    warnings = input_warnings(predictor.features, frame, shap_values,
                              predictor.unseen_categories(derived))

    prediction_id = store.new_id()
    store.put(StoredPrediction(
        prediction_id=prediction_id, task="classification", created_at=utcnow(),
        prediction=float(proba[top]), explained_class=classes[top],
        base_value=base, units=f"log-odds of {classes[top]}",
        contributions=contribution_records(predictor.features, frame, shap_values),
        reconstruction=float(base + shap_values.sum()),
        request=case.model_dump(mode="json"),
    ))

    return OutcomeResponse(
        prediction_id=prediction_id,
        predicted_outcome=classes[top],
        confidence=round(float(proba[top]), 4),
        probabilities=[
            OutcomeProbability(outcome=c, probability=round(float(p), 4))
            for c, p in sorted(zip(classes, proba), key=lambda t: -t[1])
        ],
        model_quality=_quality(predictor, "classification"),
        input_warnings=warnings,
        explain_url=f"/explain/{prediction_id}",
    )


@app.get("/explain/{prediction_id}", response_model=ExplanationResponse,
         tags=["explain"])
def explain(prediction_id: str) -> ExplanationResponse:
    """SHAP attribution for a previously returned prediction."""
    record = store.get(prediction_id)
    if record is None:
        raise HTTPException(
            status_code=404,
            detail=(
                f"prediction_id {prediction_id!r} is not in the store. The store holds "
                f"the {store.capacity} most recent predictions and is cleared when the "
                "API restarts. Make a new prediction to get a fresh id."
            ),
        )

    if record.task == "regression":
        note = ("Each SHAP value is a number of days added to or subtracted from the "
                "base value. They sum exactly to the prediction.")
    else:
        note = (f"Each SHAP value is a log-odds contribution to the "
                f"'{record.explained_class}' margin, not a probability. They sum to the "
                "class margin; the probability comes from a softmax over all classes.")

    return ExplanationResponse(
        prediction_id=record.prediction_id,
        task=record.task,
        created_at=record.created_at,
        prediction=round(record.prediction, 4),
        explained_class=record.explained_class,
        base_value=round(record.base_value, 4),
        units=record.units,
        contributions=[ShapContribution(**c) for c in record.contributions],
        reconstruction_check=round(record.reconstruction, 4),
        note=note,
    )
